import torch
from torch import nn
import torch.nn.functional as F


class FastVisualDeltaEncoder(nn.Module):
    """Tiny diff-CNN that maps adjacent visual/proprio changes to a control vector."""

    def __init__(self, motion_dim=128, proprio_dim=7, fast_encoder_type="diffcnn"):
        super().__init__()
        if fast_encoder_type != "diffcnn":
            raise NotImplementedError(f"Unsupported LR-NODE fast encoder: {fast_encoder_type}")

        self.motion_dim = motion_dim
        self.proprio_dim = proprio_dim
        self.image_encoder = nn.Sequential(
            nn.Conv2d(9, 32, 3, stride=2, padding=1),
            nn.ReLU(inplace=True),
            nn.Conv2d(32, 64, 3, stride=2, padding=1),
            nn.ReLU(inplace=True),
            nn.Conv2d(64, 128, 3, stride=2, padding=1),
            nn.ReLU(inplace=True),
            nn.AdaptiveAvgPool2d(1),
        )
        self.image_proj = nn.Linear(128, motion_dim)
        if proprio_dim > 0:
            self.proprio_proj = nn.Sequential(
                nn.Linear(proprio_dim * 3, motion_dim),
                nn.ReLU(inplace=True),
                nn.Linear(motion_dim, motion_dim),
            )
        else:
            self.proprio_proj = None
        self.out_norm = nn.LayerNorm(motion_dim)
        self.last_u_delta = None
        self.last_camera_features = None

    def _encode_camera(self, key_rgb, cur_rgb):
        if key_rgb.shape != cur_rgb.shape:
            raise ValueError(
                f"LR-NODE image delta expects matching shapes, got {tuple(key_rgb.shape)} and {tuple(cur_rgb.shape)}"
            )
        if key_rgb.dim() < 4:
            raise ValueError(f"LR-NODE image tensors must be [..., 3, H, W], got {tuple(key_rgb.shape)}")
        if key_rgb.shape[-3] != 3:
            raise ValueError(f"LR-NODE expects channel-first RGB tensors [..., 3, H, W], got {tuple(key_rgb.shape)}")

        leading_shape = key_rgb.shape[:-3]
        x = torch.cat([key_rgb, cur_rgb, cur_rgb - key_rgb], dim=-3)
        x = x.reshape(-1, x.shape[-3], x.shape[-2], x.shape[-1])
        x = F.interpolate(x, size=(64, 64), mode="bilinear", align_corners=False)
        x = self.image_encoder(x).flatten(1)
        x = self.image_proj(x)
        return x.view(*leading_shape, self.motion_dim)

    def _match_proprio_dim(self, q):
        if q.shape[-1] == self.proprio_dim:
            return q
        if q.shape[-1] > self.proprio_dim:
            return q[..., : self.proprio_dim]
        pad = self.proprio_dim - q.shape[-1]
        return F.pad(q, (0, pad))

    def forward(self, key_rgb, cur_rgb, q_key=None, q_cur=None):
        if isinstance(key_rgb, (list, tuple)):
            if not isinstance(cur_rgb, (list, tuple)) or len(key_rgb) != len(cur_rgb):
                raise ValueError("LR-NODE camera lists for key_rgb and cur_rgb must have the same length")
            image_features = [self._encode_camera(k, c) for k, c in zip(key_rgb, cur_rgb)]
            self.last_camera_features = [feat.detach() for feat in image_features]
            u_delta = torch.stack(image_features, dim=0).mean(dim=0)
        else:
            u_delta = self._encode_camera(key_rgb, cur_rgb)
            self.last_camera_features = [u_delta.detach()]

        if q_key is not None and q_cur is not None and self.proprio_proj is not None:
            if q_key.shape[:-1] != u_delta.shape[:-1] or q_cur.shape[:-1] != u_delta.shape[:-1]:
                raise ValueError(
                    "LR-NODE proprio leading dims must match visual delta dims: "
                    f"q_key={tuple(q_key.shape)}, q_cur={tuple(q_cur.shape)}, u_delta={tuple(u_delta.shape)}"
                )
            q_key = self._match_proprio_dim(q_key.to(device=u_delta.device, dtype=u_delta.dtype))
            q_cur = self._match_proprio_dim(q_cur.to(device=u_delta.device, dtype=u_delta.dtype))
            q_delta = q_cur - q_key
            u_delta = u_delta + self.proprio_proj(torch.cat([q_key, q_cur, q_delta], dim=-1))

        u_delta = self.out_norm(u_delta)
        self.last_u_delta = u_delta.detach()
        return u_delta


class ControlledLatentNODE(nn.Module):
    """Fixed-step Euler latent update used by LR-NODE."""

    def __init__(
        self,
        latent_dim,
        motion_dim=128,
        hidden_dim=256,
        gate_init_bias=-4.0,
        action_pred_steps=1,
        use_post_layernorm=0,
    ):
        super().__init__()
        self.latent_dim = latent_dim
        self.motion_dim = motion_dim
        self.time_emb_dim = 9
        self.action_pred_steps = int(action_pred_steps)
        self.use_post_layernorm = bool(use_post_layernorm)
        self.register_buffer("time_frequencies", torch.tensor([1.0, 2.0, 4.0, 8.0]), persistent=False)

        dyn_in = latent_dim + motion_dim + self.time_emb_dim * 2
        self.input_ln = nn.LayerNorm(latent_dim)
        if self.action_pred_steps > 0:
            self.action_token_embedding = nn.Embedding(self.action_pred_steps, latent_dim)
        else:
            self.action_token_embedding = None
        self.dynamics = nn.Sequential(
            nn.Linear(dyn_in, hidden_dim),
            nn.SiLU(),
            nn.Linear(hidden_dim, hidden_dim),
            nn.SiLU(),
            nn.Linear(hidden_dim, latent_dim),
        )
        gate_in = motion_dim + self.time_emb_dim
        self.gate = nn.Sequential(
            nn.Linear(gate_in, hidden_dim),
            nn.SiLU(),
            nn.Linear(hidden_dim, 1),
        )
        self.gate_bias = nn.Parameter(torch.tensor(float(gate_init_bias)))
        self.post_ln = nn.LayerNorm(latent_dim)
        self.last_gate = None
        self.last_dz = None
        self.last_update = None

    def _scalar(self, value, leading_shape, device, dtype):
        if torch.is_tensor(value):
            value = value.to(device=device, dtype=dtype)
            if value.dim() == 0:
                value = value.view(*([1] * len(leading_shape)), 1)
            elif value.shape[-1] != 1:
                value = value.unsqueeze(-1)
            while value.dim() < len(leading_shape) + 1:
                value = value.unsqueeze(-2)
            return value.expand(*leading_shape, 1)
        return torch.full((*leading_shape, 1), float(value), device=device, dtype=dtype)

    def _time_embedding(self, value, leading_shape, device, dtype):
        scalar = self._scalar(value, leading_shape, device, dtype)
        freqs = self.time_frequencies.to(device=device, dtype=dtype)
        scaled = scalar * freqs
        return torch.cat([scalar, torch.sin(scaled), torch.cos(scaled)], dim=-1)

    def _align_motion(self, z_prev, u_delta):
        z_leading = z_prev.shape[:-1]
        u_leading = u_delta.shape[:-1]
        if u_leading == z_leading:
            return u_delta
        if len(z_leading) >= 2 and u_leading == z_leading[:-1]:
            return u_delta.unsqueeze(-2).expand(*z_leading, u_delta.shape[-1])
        raise ValueError(
            "LR-NODE motion feature dims must match latent leading dims or all but the token dim: "
            f"z={tuple(z_prev.shape)}, u_delta={tuple(u_delta.shape)}"
        )

    def _add_action_token_embedding(self, z):
        if self.action_token_embedding is None:
            return z
        if z.dim() < 3 or z.shape[-2] != self.action_pred_steps:
            return z

        token_ids = torch.arange(self.action_pred_steps, device=z.device)
        token_emb = self.action_token_embedding(token_ids).to(dtype=z.dtype)
        view_shape = [1] * (z.dim() - 2) + [self.action_pred_steps, self.latent_dim]
        return z + token_emb.view(*view_shape)

    def forward(self, z_prev, u_delta, dt=1.0, age=1.0):
        if z_prev.shape[-1] != self.latent_dim:
            raise ValueError(f"LR-NODE latent dim mismatch: expected {self.latent_dim}, got {z_prev.shape[-1]}")
        if u_delta.shape[-1] != self.motion_dim:
            raise ValueError(f"LR-NODE motion dim mismatch: expected {self.motion_dim}, got {u_delta.shape[-1]}")

        z_leading = z_prev.shape[:-1]
        u_delta = self._align_motion(z_prev, u_delta).to(device=z_prev.device, dtype=z_prev.dtype)
        dt_value = self._scalar(dt, z_leading, z_prev.device, z_prev.dtype)
        dt_emb = self._time_embedding(dt, z_leading, z_prev.device, z_prev.dtype)
        age_emb = self._time_embedding(age, z_leading, z_prev.device, z_prev.dtype)

        z_flat = z_prev.reshape(-1, z_prev.shape[-1])
        u_flat = u_delta.reshape(-1, u_delta.shape[-1])
        dt_flat = dt_emb.reshape(-1, dt_emb.shape[-1])
        age_flat = age_emb.reshape(-1, age_emb.shape[-1])

        z_dyn = self._add_action_token_embedding(self.input_ln(z_prev))
        z_dyn_flat = z_dyn.reshape(-1, z_dyn.shape[-1])
        dz = self.dynamics(torch.cat([z_dyn_flat, u_flat, dt_flat, age_flat], dim=-1)).view_as(z_prev)
        gate = torch.sigmoid(self.gate(torch.cat([u_flat, age_flat], dim=-1)) + self.gate_bias)
        gate = gate.view(*z_leading, 1)
        self.last_gate = gate.detach()
        update = gate * dt_value * dz
        self.last_dz = dz.detach()
        self.last_update = update.detach()
        z_next = z_prev + update
        if self.use_post_layernorm:
            z_next = self.post_ln(z_next)
        return z_next
